/**
 * Data models for QORGAU roadside devices.
 *
 * All device states in the demo dashboard are simulated. They represent the
 * intended device lifecycle, not telemetry from installed hardware.
 */

export type DeviceState = "online" | "offline" | "maintenance" | "planned";

export interface DeviceStatus {
  id: string;
  name: string;
  roadLocationId: string;
  locationName: string;
  region: string;
  state: DeviceState;
  /** ISO timestamp of the last simulated heartbeat. */
  lastHeartbeat: string;
  firmware: string;
  powerSource: "solar-battery" | "mains" | "not-specified";
  /** True while device states are generated by the demo data layer. */
  isSimulated: boolean;
}
